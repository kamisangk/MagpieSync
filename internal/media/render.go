package media

import (
	"fmt"
	"strconv"
	"strings"
)

// DanmakuASS renders bullet comments as an ASS subtitle file. It is
// intentionally dependency-free and uses simple lane allocation suitable for
// media-server playback.
func DanmakuASS(items []Danmaku, width, height int) []byte {
	if width <= 0 {
		width = 1920
	}
	if height <= 0 {
		height = 1080
	}
	var b strings.Builder
	b.WriteString("[Script Info]\n")
	b.WriteString("; Generated by MagpieSync\n")
	b.WriteString("ScriptType: v4.00+\n")
	b.WriteString("PlayResX: " + strconv.Itoa(width) + "\n")
	b.WriteString("PlayResY: " + strconv.Itoa(height) + "\n")
	b.WriteString("WrapStyle: 0\n")
	b.WriteString("ScaledBorderAndShadow: yes\n\n")
	b.WriteString("[V4+ Styles]\n")
	b.WriteString("Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding\n")
	b.WriteString("Style: Danmaku,Microsoft YaHei,36,&H00FFFFFF,&H00FFFFFF,&H00000000,&H64000000,0,0,0,0,100,100,0,0,1,2,0,7,20,20,20,1\n\n")
	b.WriteString("[Events]\n")
	b.WriteString("Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text\n")

	laneTop := make([]int64, max(1, height/48))
	laneBottom := make([]int64, max(1, height/48))
	scrollDuration := int64(8000)
	fixedDuration := int64(4000)
	for _, d := range items {
		text := strings.TrimSpace(d.Content)
		if text == "" || d.Progress < 0 {
			continue
		}
		text = strings.ReplaceAll(text, "\\", "\\\\")
		text = strings.ReplaceAll(text, "{", "\\{")
		text = strings.ReplaceAll(text, "}", "\\}")
		text = strings.ReplaceAll(text, "\n", "\\N")
		color := fmt.Sprintf("&H%02X%02X%02X&", d.Color&0xff, (d.Color>>8)&0xff, (d.Color>>16)&0xff)
		fontSize := d.FontSize
		if fontSize < 12 || fontSize > 72 {
			fontSize = 30
		}
		start := d.Progress
		lane := int64(0)
		fixed := false
		switch d.Mode {
		case 4:
			fixed = true
			lane = pickLane(laneBottom, start, fixedDuration)
			text = fmt.Sprintf("{\\an2\\pos(%d,%d)\\c%s\\fs%d}%s", width/2, height-40-int(lane)*48, color, fontSize, text)
		case 5:
			fixed = true
			lane = pickLane(laneTop, start, fixedDuration)
			text = fmt.Sprintf("{\\an8\\pos(%d,%d)\\c%s\\fs%d}%s", width/2, 20+int(lane)*48, color, fontSize, text)
		default:
			lane = pickLane(laneTop, start, scrollDuration)
			y := 24 + int(lane)*48
			text = fmt.Sprintf("{\\an7\\move(%d,%d,-%d,%d)\\c%s\\fs%d}%s", width+20, y, width+400, y, color, fontSize, text)
		}
		end := start + scrollDuration
		if fixed {
			end = start + fixedDuration
		}
		b.WriteString(fmt.Sprintf("Dialogue: 0,%s,%s,Danmaku,,0,0,0,,%s\n",
			assTime(start), assTime(end), text))
	}
	return []byte(b.String())
}

func pickLane(lanes []int64, start, duration int64) int64 {
	for i := range lanes {
		if lanes[i] <= start {
			lanes[i] = start + duration
			return int64(i)
		}
	}
	// All lanes are occupied: reuse the earliest one and accept overlap.
	best := 0
	for i := range lanes {
		if lanes[i] < lanes[best] {
			best = i
		}
	}
	lanes[best] = start + duration
	return int64(best)
}

func assTime(ms int64) string {
	if ms < 0 {
		ms = 0
	}
	h := ms / 3600000
	m := (ms % 3600000) / 60000
	s := (ms % 60000) / 1000
	cs := (ms % 1000) / 10
	return fmt.Sprintf("%d:%02d:%02d.%02d", h, m, s, cs)
}

// SubtitleSRT renders subtitle items as SubRip text.
func SubtitleSRT(items []SubtitleItem) []byte {
	var b strings.Builder
	for i, item := range items {
		text := strings.TrimSpace(item.Content)
		if text == "" {
			continue
		}
		b.WriteString(strconv.Itoa(i + 1))
		b.WriteString("\n")
		b.WriteString(srtTime(item.From))
		b.WriteString(" --> ")
		b.WriteString(srtTime(item.To))
		b.WriteString("\n")
		b.WriteString(text)
		b.WriteString("\n\n")
	}
	return []byte(b.String())
}

func srtTime(sec float64) string {
	if sec < 0 {
		sec = 0
	}
	ms := int64(sec*1000 + 0.5)
	h := ms / 3600000
	m := (ms % 3600000) / 60000
	s := (ms % 60000) / 1000
	ms %= 1000
	return fmt.Sprintf("%02d:%02d:%02d,%03d", h, m, s, ms)
}
