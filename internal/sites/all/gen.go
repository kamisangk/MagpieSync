//go:build ignore

// Command gen regenerates the build-tag manifest under internal/sites/all.
//
// Every plugin directory must declare the same //go:build constraint on its
// files. The generated manifest copies that constraint verbatim, so adding a
// site is just dropping a directory and re-running generation — `make build`
// and the Docker build do this automatically.
//
// Run it from anywhere:
//
//	go run ./internal/sites/all/gen.go
//	go generate ./internal/sites/all
package main

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"runtime"
	"sort"
	"strings"
)

const generatedHeader = "// Code generated by internal/sites/all/gen.go; DO NOT EDIT."

func main() {
	_, file, _, ok := runtime.Caller(0)
	if !ok {
		fail("cannot locate gen.go")
	}
	root := filepath.Dir(file)
	for i := 0; i < 3; i++ { // all -> sites -> internal -> repository root
		root = filepath.Dir(root)
	}
	pluginsDir := filepath.Join(root, "internal", "sites", "plugins")
	allDir := filepath.Join(root, "internal", "sites", "all")

	entries, err := os.ReadDir(pluginsDir)
	if err != nil {
		fail("read plugins: " + err.Error())
	}

	expected := map[string]bool{}
	names := make([]string, 0, len(entries))
	for _, entry := range entries {
		if entry.IsDir() {
			names = append(names, entry.Name())
		}
	}
	sort.Strings(names)

	for _, name := range names {
		constraint, err := pluginConstraint(filepath.Join(pluginsDir, name))
		if err != nil {
			fail(err.Error())
		}
		manifest := render(name, constraint)
		path := filepath.Join(allDir, name+".go")
		expected[name+".go"] = true

		current, readErr := os.ReadFile(path)
		if readErr == nil && bytes.Equal(current, manifest) {
			continue
		}
		if err := os.WriteFile(path, manifest, 0o644); err != nil {
			fail("write " + path + ": " + err.Error())
		}
		fmt.Println("wrote", filepath.ToSlash(filepath.Join("internal", "sites", "all", name+".go")))
	}

	// Drop manifests whose plugin directory was renamed or removed. Only files
	// carrying the generated header are touched; hand-written files are safe.
	allEntries, err := os.ReadDir(allDir)
	if err != nil {
		fail("read all dir: " + err.Error())
	}
	for _, entry := range allEntries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".go") || expected[entry.Name()] {
			continue
		}
		data, err := os.ReadFile(filepath.Join(allDir, entry.Name()))
		if err != nil {
			fail("read " + entry.Name() + ": " + err.Error())
		}
		if !bytes.HasPrefix(data, []byte(generatedHeader)) {
			continue
		}
		if err := os.Remove(filepath.Join(allDir, entry.Name())); err != nil {
			fail("remove stale " + entry.Name() + ": " + err.Error())
		}
		fmt.Println("removed stale internal/sites/all/" + entry.Name())
	}
}

// pluginConstraint returns the single build constraint shared by every Go file
// in the plugin directory. Mixed constraints are an error rather than a guess.
func pluginConstraint(dir string) (string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return "", fmt.Errorf("read %s: %w", dir, err)
	}
	constraint := ""
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".go") {
			continue
		}
		data, err := os.ReadFile(filepath.Join(dir, entry.Name()))
		if err != nil {
			return "", fmt.Errorf("read %s/%s: %w", dir, entry.Name(), err)
		}
		found, err := buildConstraint(data)
		if err != nil {
			if entry.Name() == "doc.go" {
				continue
			}
			return "", fmt.Errorf("%s/%s: %w", dir, entry.Name(), err)
		}
		if constraint == "" {
			constraint = found
			continue
		}
		if constraint != found {
			return "", fmt.Errorf("%s: files disagree on the build constraint: %q vs %q", dir, constraint, found)
		}
	}
	if constraint == "" {
		return "", fmt.Errorf("%s: no Go files with a //go:build constraint", dir)
	}
	return constraint, nil
}

func buildConstraint(src []byte) (string, error) {
	for _, raw := range strings.Split(string(src), "\n") {
		line := strings.TrimSpace(raw)
		if strings.HasPrefix(line, "//go:build ") {
			return strings.TrimSpace(strings.TrimPrefix(line, "//go:build ")), nil
		}
		if strings.HasPrefix(line, "package ") {
			break
		}
	}
	return "", fmt.Errorf("missing //go:build constraint")
}

func render(name, constraint string) []byte {
	var b bytes.Buffer
	fmt.Fprintf(&b, "%s\n", generatedHeader)
	fmt.Fprintf(&b, "// Source: internal/sites/plugins/%s\n", name)
	fmt.Fprintf(&b, "\n//go:build %s\n\n", constraint)
	b.WriteString("package all\n\n")
	b.WriteString("import (\n")
	fmt.Fprintf(&b, "\t_ \"magpiesync/internal/sites/plugins/%s\"\n", name)
	b.WriteString(")\n")
	return b.Bytes()
}

func fail(message string) {
	fmt.Fprintln(os.Stderr, "sites-gen:", message)
	os.Exit(1)
}
